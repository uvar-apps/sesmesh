"""Turn the repository's validation data into LaTeX tables, macros and
pgfplots data files for the paper.

Inputs (read only):
  docs/validation/accuracy.csv   53-entry accuracy study (xtask validate)
  docs/validation/sweep.csv      200-entry robustness sweep (xtask sweep)
  docs/validation/large.csv      large inputs (manual runs)
  paper/data/analytic.csv        one/two-sphere references (paper/scripts/analytic)
  paper/data/scaling.csv         thread scaling (Design §11.1, transcribed)

Outputs: paper/generated/*.tex and *.dat. Standard library only, so the
paper builds without a Python environment beyond python3 itself.

Usage: python3 paper/scripts/make_data.py   (from any directory)
"""

import csv
import math
import statistics as st
from collections.abc import Sequence
from decimal import ROUND_HALF_UP, Decimal
from pathlib import Path

PAPER = Path(__file__).resolve().parent.parent
REPO = PAPER.parent
VAL = REPO / "docs" / "validation"
OUT = PAPER / "generated"

HEADER = (
    "% sesmesh — Solvent Excluded Surface meshes for molecules\n"
    "% Copyright (c) 2026 Ugo Varetto\n"
    "% SPDX-License-Identifier: MIT OR Apache-2.0\n"
    "% Generated by paper/scripts/make_data.py — do not edit.\n"
)
DAT_HEADER = "# Generated by paper/scripts/make_data.py — do not edit.\n"

macros: dict[str, str] = {}


def val(key: str, text: str) -> None:
    """Record a macro, used in the text as \\val{key}."""
    macros[key] = text


def pct(x: float, digits: int = 2) -> str:
    """Relative error as a signed percentage with a proper minus sign."""
    s = f"{100 * x:+.{digits}f}"
    return s.replace("-", "$-$").replace("+", "$+$") if x != 0 else f"{0:.{digits}f}"


def pct_plain(x: float, digits: int = 2) -> str:
    return f"{100 * x:.{digits}f}"


def thousands(n: int) -> str:
    """12345 -> 12\\,345 (thin space, as in the docs)."""
    s = f"{n:,}"
    return s.replace(",", "\\,")


def fmt_h(h: float) -> str:
    return f"{h:g}"


def round1(x: str) -> str:
    """One decimal, half up (13.25 -> 13.3), as in the validation report."""
    return str(Decimal(x).quantize(Decimal("0.1"), rounding=ROUND_HALF_UP))


def read(path: Path) -> list[dict[str, str]]:
    with path.open(newline="") as f:
        return list(csv.DictReader(f))


def write(name: str, text: str, header: str = HEADER) -> None:
    (OUT / name).write_text(header + text)


def loglog_slope(xs: Sequence[float], ys: Sequence[float]) -> float:
    lx = [math.log(x) for x in xs]
    ly = [math.log(y) for y in ys]
    mx, my = st.mean(lx), st.mean(ly)
    num = sum((a - mx) * (b - my) for a, b in zip(lx, ly))
    den = sum((a - mx) ** 2 for a in lx)
    return num / den


# ---------------------------------------------------------------- accuracy
def accuracy() -> None:
    rows = read(VAL / "accuracy.csv")
    entries = sorted({r["entry"] for r in rows})
    hs = sorted({float(r["spacing"]) for r in rows}, reverse=True)
    val("corpus-n", str(len(entries)))
    by_atoms = sorted({(int(r["atoms"]), r["entry"]) for r in rows})
    val("corpus-atoms-min", thousands(by_atoms[0][0]))
    val("corpus-atoms-min-id", by_atoms[0][1])
    val("corpus-atoms-max", thousands(by_atoms[-1][0]))
    val("corpus-atoms-max-id", by_atoms[-1][1])

    acc_lines = []
    den_lines = []
    summary = ["h area_mean area_min area_max vol_mean vol_min vol_max"]
    pooled = []
    for h in hs:
        sel = [r for r in rows if float(r["spacing"]) == h]
        a = [float(r["area_err"]) for r in sel]
        v = [float(r["volume_err"]) for r in sel]
        d = [float(r["vertices_h2_per_area"]) for r in sel]
        if h <= 0.5:
            pooled += d
        k = fmt_h(h)
        val(f"area-mean-{k}", pct(st.mean(a)))
        val(f"area-worst-{k}", pct(min(a)))
        val(f"vol-mean-{k}", pct(st.mean(v)))
        val(f"vol-worst-{k}", pct(min(v)))
        val(f"vol-max-{k}", pct(max(v)))
        val(f"dens-mean-{k}", f"{st.mean(d):.4f}")
        val(f"dens-sd-{k}", f"{st.stdev(d):.4f}")
        acc_lines.append(
            f"{h:.2f} & {pct(st.mean(a))} & {pct(min(a))} & "
            f"{pct(st.mean(v))} & {pct(min(v))} & {pct(max(v))} \\\\"
        )
        den_lines.append(
            f"{h:.2f} & {st.mean(d):.4f} & {st.stdev(d):.4f} & "
            f"{min(d):.3f}--{max(d):.3f} \\\\"
        )
        summary.append(
            f"{h} {100 * st.mean(a):.4f} {100 * min(a):.4f} {100 * max(a):.4f} "
            f"{100 * st.mean(v):.4f} {100 * min(v):.4f} {100 * max(v):.4f}"
        )
    val("dens-pooled-mean", f"{st.mean(pooled):.4f}")
    val("dens-pooled-sd", f"{st.stdev(pooled):.4f}")

    mean_at = {
        h: st.mean(float(r["area_err"]) for r in rows if float(r["spacing"]) == h)
        for h in hs
    }
    val("area-ratio-half", f"{mean_at[0.5] / mean_at[0.25]:.2f}")
    # Observed order of the mean area error between h = 1 and 0.25 Å.
    order = loglog_slope(
        [h for h in hs], [abs(mean_at[h]) for h in hs]
    )
    val("area-order", f"{order:.2f}")

    write("tab-accuracy.tex", "\n".join(acc_lines) + "\n")
    write("tab-density.tex", "\n".join(den_lines) + "\n")
    write("conv-summary.dat", "\n".join(summary) + "\n", DAT_HEADER)

    # Per-entry absolute errors for the scatter plot.
    lines = ["h area vol atoms"]
    for r in rows:
        lines.append(
            f"{r['spacing']} {abs(100 * float(r['area_err'])):.5f} "
            f"{abs(100 * float(r['volume_err'])):.5f} {r['atoms']}"
        )
    write("conv-entries.dat", "\n".join(lines) + "\n", DAT_HEADER)

    # Time vs atoms at 0.25 Å (accuracy corpus).
    t = ["atoms seconds triangles"]
    q = [r for r in rows if float(r["spacing"]) == 0.25]
    for r in sorted(q, key=lambda r: int(r["atoms"])):
        t.append(f"{r['atoms']} {r['seconds']} {r['triangles']}")
    write("time-corpus.dat", "\n".join(t) + "\n", DAT_HEADER)
    val(
        "corpus-time-slope",
        f"{loglog_slope([int(r['atoms']) for r in q], [float(r['seconds']) for r in q]):.2f}",
    )
    val(
        "corpus-tri-slope",
        f"{loglog_slope([int(r['atoms']) for r in q], [int(r['triangles']) for r in q]):.2f}",
    )

    # Appendix: one row per entry at 0.25 Å, with the 0.5 Å errors.
    half = {r["entry"]: r for r in rows if float(r["spacing"]) == 0.5}
    app = []
    for r in sorted(q, key=lambda r: (int(r["atoms"]), r["entry"])):
        area = float(r["area"])
        a0 = area / (1 + float(r["area_err"]))
        h5 = half[r["entry"]]
        cav = int(r["cavities"])
        app.append(
            f"{r['entry']} & {thousands(int(r['atoms']))} & "
            f"{thousands(int(r['triangles']))} & {cav} & "
            f"{thousands(round(a0))} & "
            f"{pct(float(h5['area_err']))} & {pct(float(r['area_err']))} & "
            f"{pct(float(h5['volume_err']))} & {pct(float(r['volume_err']))} & "
            f"{float(r['seconds']):.2f} \\\\"
        )
    write("tab-corpus.tex", "\n".join(app) + "\n")


# ------------------------------------------------------------------- sweep
def sweep() -> None:
    rows = read(VAL / "sweep.csv")
    ok = [r for r in rows if r["status"] == "ok"]
    atoms = [int(r["atoms"]) for r in rows]
    val("sweep-n", str(len(rows)))
    val("sweep-ok", str(len(ok)))
    val("sweep-atoms-min", thousands(min(atoms)))
    val("sweep-atoms-max", thousands(max(atoms)))
    val("sweep-atoms-median", thousands(round(st.median(atoms))))
    val("sweep-cavities", thousands(sum(int(r["cavities"]) for r in rows)))
    val("sweep-components-max", thousands(max(int(r["components"]) for r in rows)))
    secs = [float(r["seconds"]) for r in rows]
    val("sweep-seconds-total", f"{sum(secs):.0f}")
    val("sweep-seconds-max", f"{max(secs):.1f}")
    big = max(rows, key=lambda r: int(r["atoms"]))
    val("sweep-largest-id", big["entry"])
    val("sweep-largest-seconds", round1(big["seconds"]))
    slow = max(rows, key=lambda r: float(r["seconds"]))
    val("sweep-slowest-id", slow["entry"])
    val("sweep-slowest-atoms", thousands(int(slow["atoms"])))
    val("sweep-slowest-tri", f"{int(slow['triangles']) / 1e6:.1f}")
    val(
        "sweep-time-slope",
        f"{loglog_slope(atoms, secs):.2f}",
    )
    lines = ["atoms seconds triangles components cavities"]
    for r in sorted(rows, key=lambda r: int(r["atoms"])):
        lines.append(
            f"{r['atoms']} {r['seconds']} {r['triangles']} "
            f"{r['components']} {r['cavities']}"
        )
    write("sweep.dat", "\n".join(lines) + "\n", DAT_HEADER)


