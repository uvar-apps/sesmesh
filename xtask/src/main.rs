//! Development automation for the sesmesh workspace.
//!
//! Run through the Cargo alias: `cargo xtask <command>`.
//!
//! * `cargo xtask sets` — list the data sets defined in `tests/data/sets.toml`.
//! * `cargo xtask fetch --set <name>` — download a set into
//!   `tests/data/cache/` and verify it against `tests/data/sets.lock`.
//! * `cargo xtask sample-sweep --count N --seed S` — record N random current
//!   PDB entries as the `sweep` set (Plan T9.4).
//! * `cargo xtask validate` / `cargo xtask sweep` — the accuracy study and the
//!   robustness sweep of Plan Phase 9 (run with `--release`:
//!   `cargo run --release -p xtask -- validate`).

mod campaign;

use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::fs;
use std::io::{ErrorKind, Read};
use std::path::{Path, PathBuf};
use std::process::Command;

use anyhow::{Context, Result, bail, ensure};
use clap::{Parser, Subcommand};
use serde::{Deserialize, Serialize};
use sha2::{Digest, Sha256};

/// Development automation for sesmesh.
#[derive(Debug, Parser)]
#[command(name = "xtask")]
struct Cli {
    #[command(subcommand)]
    command: Cmd,
}

#[derive(Debug, Subcommand)]
enum Cmd {
    /// List the data sets defined in tests/data/sets.toml.
    Sets,
    /// Download data sets into tests/data/cache/ and verify their checksums.
    Fetch {
        /// Set to download (repeatable); `all` downloads every set.
        #[arg(long = "set", required = true)]
        sets: Vec<String>,
        /// Record new checksums when upstream files changed (review first).
        #[arg(long)]
        update_lock: bool,
        /// Download again even when a verified copy is cached.
        #[arg(long)]
        force: bool,
    },
    /// Record a reproducible random sample of current PDB entries as the
    /// `sweep` set in tests/data/sets.toml.
    SampleSweep {
        /// Number of entries.
        #[arg(long, default_value_t = 200)]
        count: usize,
        /// Random seed.
        #[arg(long, default_value_t = 2026)]
        seed: u64,
    },
    /// Accuracy study on the validation set (Plan T9.3, T9.5): area and
    /// volume vs grid spacing, extrapolated to h → 0; writes
    /// docs/validation/accuracy.csv.
    Validate {
        /// Grid spacings (Å), coarse to fine.
        #[arg(long, value_delimiter = ',', default_value = "1.0,0.7,0.5,0.35,0.25")]
        spacings: Vec<f64>,
        /// Skip entries with more atoms than this at the finest spacing.
        #[arg(long, default_value_t = 300_000)]
        max_atoms: usize,
    },
    /// Robustness sweep over the `sweep` set (Plan T9.4) at one spacing;
    /// writes docs/validation/sweep.csv.
    Sweep {
        /// Grid spacing (Å).
        #[arg(long, default_value_t = 0.5)]
        spacing: f64,
        /// Use 1.0 Å above this many atoms.
        #[arg(long, default_value_t = 200_000)]
        coarse_above: usize,
    },
}

/// `tests/data/sets.toml`: human-edited list of download sets.
#[derive(Debug, Deserialize)]
struct SetsFile {
    base_url: String,
    sets: BTreeMap<String, DataSet>,
}

#[derive(Debug, Deserialize)]
struct DataSet {
    description: String,
    files: Vec<String>,
}

/// `tests/data/sets.lock`: machine-written SHA-256 checksums.
#[derive(Debug, Default, Serialize, Deserialize)]
struct LockFile {
    files: BTreeMap<String, String>,
}

const LOCK_HEADER: &str = "# Generated by `cargo xtask fetch`. Do not edit by hand.\n\
                           # SHA-256 of every downloaded data file (see tests/data/README.md).\n\n";

fn main() -> Result<()> {
    let cli = Cli::parse();
    let data_dir = workspace_root().join("tests").join("data");
    let sets: SetsFile = toml::from_str(
        &fs::read_to_string(data_dir.join("sets.toml")).context("reading tests/data/sets.toml")?,
    )
    .context("parsing tests/data/sets.toml")?;

    match cli.command {
        Cmd::Sets => {
            for (name, set) in &sets.sets {
                println!("{name:12} {:3} files  {}", set.files.len(), set.description);
            }
            Ok(())
        }
        Cmd::Fetch {
            sets: requested,
            update_lock,
            force,
        } => fetch(&data_dir, &sets, &requested, update_lock, force),
        Cmd::SampleSweep { count, seed } => campaign::sample_sweep(&data_dir, count, seed),
        Cmd::Validate {
            spacings,
            max_atoms,
        } => campaign::validate(
            &workspace_root(),
            &sets.sets["validation"].files,
            &spacings,
            max_atoms,
        ),
        Cmd::Sweep {
            spacing,
            coarse_above,
        } => {
            let files = sets
                .sets
                .get("sweep")
                .map(|s| s.files.clone())
                .context("no `sweep` set: run `cargo xtask sample-sweep` first")?;
            campaign::sweep(&workspace_root(), &files, spacing, coarse_above)
        }
    }
}

fn workspace_root() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .expect("xtask lives one level below the workspace root")
        .to_path_buf()
}

fn fetch(
    data_dir: &Path,
    sets: &SetsFile,
    requested: &[String],
    update_lock: bool,
    force: bool,
) -> Result<()> {
    let mut files: Vec<&str> = Vec::new();
    for name in requested {
        if name == "all" {
            files.extend(
                sets.sets
                    .values()
                    .flat_map(|s| s.files.iter().map(String::as_str)),
            );
            continue;
        }
        let Some(set) = sets.sets.get(name) else {
            let known: Vec<&str> = sets.sets.keys().map(String::as_str).collect();
            bail!("unknown set `{name}` (known: {})", known.join(", "));
        };
        files.extend(set.files.iter().map(String::as_str));
    }
    files.sort_unstable();
    files.dedup();

    let lock_path = data_dir.join("sets.lock");
    let mut lock: LockFile = match fs::read_to_string(&lock_path) {
        Ok(text) => toml::from_str(&text).context("parsing tests/data/sets.lock")?,
        Err(e) if e.kind() == ErrorKind::NotFound => LockFile::default(),
        Err(e) => return Err(e).context("reading tests/data/sets.lock"),
    };
    let cache = data_dir.join("cache");
    fs::create_dir_all(&cache).context("creating tests/data/cache")?;

    let mut lock_changed = false;
    for file in files {
        ensure!(
            !file.is_empty()
                && file
                    .bytes()
                    .all(|b| b.is_ascii_alphanumeric() || matches!(b, b'.' | b'-' | b'_')),
            "invalid file name `{file}` in sets.toml"
        );
        let target = cache.join(file);
        let expected = lock.files.get(file).cloned();

        if !force && target.exists() {
            let actual = sha256_file(&target)?;
            if expected.as_deref() == Some(actual.as_str()) {
                println!("ok      {file} (cached)");
                continue;
            }
        }

        let url = format!("{}{file}", sets.base_url);
        let part = cache.join(format!("{file}.part"));
        download(&url, &part)?;
        let actual = sha256_file(&part)?;
        match expected {
            Some(ref e) if *e == actual => println!("fetched {file}"),
            Some(_) if !update_lock => {
                fs::remove_file(&part).ok();
                bail!(
                    "checksum mismatch for {file}: upstream file changed. \
                     Review the change, then rerun with --update-lock"
                );
            }
            Some(_) => {
                println!("fetched {file} (checksum updated)");
                lock.files.insert(file.to_owned(), actual);
                lock_changed = true;
            }
            None => {
                println!("fetched {file} (new checksum recorded)");
                lock.files.insert(file.to_owned(), actual);
                lock_changed = true;
            }
        }
        fs::rename(&part, &target).with_context(|| format!("moving {file} into the cache"))?;
    }

    if lock_changed {
        let body = toml::to_string(&lock).context("serializing sets.lock")?;
        fs::write(&lock_path, format!("{LOCK_HEADER}{body}")).context("writing sets.lock")?;
        println!("updated tests/data/sets.lock; commit it together with sets.toml");
    }
    Ok(())
}

pub(crate) fn download(url: &str, dest: &Path) -> Result<()> {
    let status = Command::new("curl")
        .args([
            "--fail",
            "--silent",
            "--show-error",
            "--location",
            "--retry",
            "3",
            "--user-agent",
            "sesmesh-xtask",
            "--output",
        ])
        .arg(dest)
        .arg(url)
        .status()
        .context("running `curl` (is it installed and on PATH?)")?;
    if !status.success() {
        fs::remove_file(dest).ok();
        bail!("download failed ({status}): {url}");
    }
    Ok(())
}

fn sha256_file(path: &Path) -> Result<String> {
    let mut file = fs::File::open(path).with_context(|| format!("opening {}", path.display()))?;
    let mut hasher = Sha256::new();
    let mut buf = vec![0u8; 1 << 16];
    loop {
        let n = file.read(&mut buf)?;
        if n == 0 {
            break;
        }
        hasher.update(&buf[..n]);
    }
    let mut hex = String::with_capacity(64);
    for byte in hasher.finalize() {
        write!(hex, "{byte:02x}").expect("writing to a String cannot fail");
    }
    Ok(hex)
}
